/**
 * Calcular se um numero é positivo, negativo ou zero: 
 * ENTRADA: Um numero
 * LOGICA: 
 *  * LOGICA: 
 *    - ???
 * VALIDAÇÃO: 
 */

const numero = prompt("Ingresse um numero:");

if (numero == 0) {
    alert("O numero ingressado é Zero.")
}


if (numero > 0) {
    alert("O numero ingressado é Positivo.")
}

if (numero < 0) {
    alert("O numero ingressado é Negativo.")
}

