/**
 * Computar se a letra ingressada é uma vocal: 
 * ENTRADA: Letra
 * LOGICA: 
 *  * LOGICA: 
 *    - ???
 * SAIDA: memsagem
 */

let letra = prompt("Ingresse uma letra:");

if (letra == "a" || letra == "e" 
    || letra == "i" || letra == "o" 
    || letra == "u") 
{
    alert("É vogal.");
}

if (letra != "a" && letra != "e" 
    && letra != "i" && letra != "o" 
    && letra != "u") 
{
    alert("Não é uma vogal.");
}


